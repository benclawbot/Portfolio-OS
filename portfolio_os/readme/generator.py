from __future__ import annotations

import json
import os
import re
import tempfile
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from portfolio_os.models import RepositoryAnalysis
from .banner import extract_hero_banner

GENERATED_MARKER = "<!-- Generated by Portfolio OS from repository evidence. -->"


class ReadmeGenerationError(RuntimeError):
    pass


@dataclass(frozen=True)
class ProjectMetadata:
    name: str
    description: str | None = None
    version: str | None = None


class ReadmeGenerator:
    def __init__(self, preserve_hero: bool = True) -> None:
        self.preserve_hero = preserve_hero

    def generate(self, root: Path, analysis: RepositoryAnalysis) -> str:
        root = root.expanduser().resolve()
        if analysis.errors:
            names = ", ".join(error["analyzer"] for error in analysis.errors)
            raise ReadmeGenerationError(f"Cannot generate README while analyzers failed: {names}")
        if Path(analysis.root).resolve() != root:
            raise ReadmeGenerationError("Analysis root does not match the requested repository")

        metadata = self._metadata(root, analysis)
        existing = self._read_existing(root)
        hero = extract_hero_banner(existing) if self.preserve_hero else ""
        sections = [GENERATED_MARKER]
        if hero:
            sections.extend([hero, ""])
        sections.extend([f"# {metadata.name}", "", self._overview(metadata, analysis), ""])
        sections.extend(self._evidence_section(analysis))
        sections.extend(self._stack_section(analysis))
        sections.extend(self._architecture_section(analysis))
        sections.extend(self._install_section(analysis))
        sections.extend(self._usage_section(analysis))
        sections.extend(self._testing_section(analysis))
        sections.extend(self._limitations_section())
        if (root / "LICENSE").exists() or any(root.glob("LICENSE.*")):
            sections.extend(["## License", "", "See the repository license file for terms.", ""])
        return self._normalize("\n".join(sections))

    def write(self, root: Path, content: str, target: str = "README.md") -> Path:
        root = root.expanduser().resolve()
        destination = root / target
        destination.parent.mkdir(parents=True, exist_ok=True)
        fd, temporary_name = tempfile.mkstemp(prefix=f".{destination.name}.", dir=destination.parent, text=True)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary_name, destination)
        except Exception:
            try:
                os.unlink(temporary_name)
            except FileNotFoundError:
                pass
            raise
        return destination

    def _read_existing(self, root: Path) -> str:
        for name in ("README.md", "Readme.md", "readme.md"):
            path = root / name
            if path.exists():
                return path.read_text(encoding="utf-8", errors="replace")
        return ""

    def _metadata(self, root: Path, analysis: RepositoryAnalysis) -> ProjectMetadata:
        name = analysis.repository.replace("_", " ").strip() or root.name
        description = None
        version = None
        pyproject = root / "pyproject.toml"
        if pyproject.exists():
            project = tomllib.loads(pyproject.read_text(encoding="utf-8")).get("project", {})
            name = str(project.get("name") or name)
            description = self._clean_description(project.get("description"))
            version = str(project["version"]) if project.get("version") else None
        package = root / "package.json"
        if package.exists():
            data = json.loads(package.read_text(encoding="utf-8"))
            name = str(data.get("displayName") or data.get("name") or name)
            description = description or self._clean_description(data.get("description"))
            version = version or (str(data["version"]) if data.get("version") else None)
        cargo = root / "Cargo.toml"
        if cargo.exists():
            package_data = tomllib.loads(cargo.read_text(encoding="utf-8")).get("package", {})
            name = str(package_data.get("name") or name)
            description = description or self._clean_description(package_data.get("description"))
            version = version or (str(package_data["version"]) if package_data.get("version") else None)
        return ProjectMetadata(name=name, description=description, version=version)

    def _clean_description(self, value: Any) -> str | None:
        if not isinstance(value, str):
            return None
        cleaned = " ".join(value.split())
        return cleaned.rstrip(".") + "." if cleaned else None

    def _overview(self, metadata: ProjectMetadata, analysis: RepositoryAnalysis) -> str:
        if metadata.description:
            return metadata.description
        languages = analysis.facts.get("languages", {})
        primary = languages.get("primary")
        frameworks = analysis.facts.get("manifests", {}).get("frameworks", [])
        details = []
        if primary:
            details.append(f"implemented primarily in {primary}")
        if frameworks:
            details.append("using " + ", ".join(frameworks[:4]))
        suffix = " and ".join(details) if details else "with source files detected in this repository"
        return f"{metadata.name} is a software project {suffix}."

    def _evidence_section(self, analysis: RepositoryAnalysis) -> list[str]:
        repository = analysis.facts.get("repository", {})
        quality = analysis.facts.get("quality", {})
        lines = ["## Repository evidence", ""]
        facts = [
            ("Source files", repository.get("file_count")),
            ("Detected tests", quality.get("test_file_count")),
            ("CI workflows", len(quality.get("workflows", []))),
        ]
        for label, value in facts:
            if value is not None:
                lines.append(f"- **{label}:** {value}")
        entry_points = repository.get("entry_points", [])
        if entry_points:
            lines.append("- **Entry points:** " + ", ".join(f"`{path}`" for path in entry_points[:12]))
        lines.append("")
        return lines

    def _stack_section(self, analysis: RepositoryAnalysis) -> list[str]:
        languages = analysis.facts.get("languages", {})
        manifests = analysis.facts.get("manifests", {})
        lines = ["## Technology stack", ""]
        primary = languages.get("primary")
        if primary:
            lines.append(f"- **Primary language:** {primary}")
        detected = languages.get("detected", [])
        if detected:
            lines.append("- **Detected languages:** " + ", ".join(detected))
        ecosystems = manifests.get("ecosystems", [])
        if ecosystems:
            lines.append("- **Build ecosystems:** " + ", ".join(ecosystems))
        frameworks = manifests.get("frameworks", [])
        if frameworks:
            lines.append("- **Detected frameworks/libraries:** " + ", ".join(f"`{item}`" for item in frameworks))
        lockfiles = manifests.get("lockfiles", [])
        if lockfiles:
            lines.append("- **Lockfiles:** " + ", ".join(f"`{item}`" for item in lockfiles))
        lines.append("")
        return lines

    def _architecture_section(self, analysis: RepositoryAnalysis) -> list[str]:
        repository = analysis.facts.get("repository", {})
        directories = repository.get("top_level_directories", [])
        if not directories:
            return []
        lines = ["## Repository structure", "", "```text", f"{analysis.repository}/"]
        lines.extend(f"├── {name}/" for name in directories[:16])
        lines.extend(["```", ""])
        return lines

    def _install_section(self, analysis: RepositoryAnalysis) -> list[str]:
        manifests = analysis.facts.get("manifests", {})
        ecosystems = set(manifests.get("ecosystems", []))
        lockfiles = set(manifests.get("lockfiles", []))
        commands: list[str] = []
        if "Python" in ecosystems:
            commands.extend(["python -m venv .venv", "python -m pip install -e ."])
        if "Node.js" in ecosystems:
            install = "npm ci" if "package-lock.json" in lockfiles else "npm install"
            if "pnpm-lock.yaml" in lockfiles:
                install = "pnpm install --frozen-lockfile"
            elif "yarn.lock" in lockfiles:
                install = "yarn install --frozen-lockfile"
            elif "bun.lockb" in lockfiles:
                install = "bun install --frozen-lockfile"
            commands.append(install)
        if "Rust" in ecosystems:
            commands.append("cargo build --locked")
        if "Flutter/Dart" in ecosystems:
            commands.append("flutter pub get")
        if "Go" in ecosystems:
            commands.append("go mod download")
        if not commands:
            return []
        return ["## Installation", "", "```bash", *commands, "```", ""]

    def _usage_section(self, analysis: RepositoryAnalysis) -> list[str]:
        commands = analysis.facts.get("manifests", {}).get("commands", {})
        if not commands:
            return []
        lines = ["## Available commands", "", "| Command | Evidence |", "|---|---|"]
        for name, command in sorted(commands.items()):
            if re.match(r"^[A-Za-z0-9_.:-]+$", name):
                escaped = str(command).replace("|", "\\|")
                lines.append(f"| `{name}` | `{escaped}` |")
        lines.append("")
        return lines

    def _testing_section(self, analysis: RepositoryAnalysis) -> list[str]:
        quality = analysis.facts.get("quality", {})
        manifests = analysis.facts.get("manifests", {})
        if not quality.get("test_file_count"):
            return []
        ecosystems = set(manifests.get("ecosystems", []))
        commands = manifests.get("commands", {})
        tests: list[str] = []
        if "test" in commands:
            tests.append("npm test")
        if "Python" in ecosystems:
            tests.append("python -m pytest")
        if "Rust" in ecosystems:
            tests.append("cargo test --locked")
        if "Flutter/Dart" in ecosystems:
            tests.append("flutter test")
        if "Go" in ecosystems:
            tests.append("go test ./...")
        tests = list(dict.fromkeys(tests))
        if not tests:
            return ["## Testing", "", f"The repository contains {quality['test_file_count']} detected test file(s).", ""]
        return ["## Testing", "", "```bash", *tests, "```", ""]

    def _limitations_section(self) -> list[str]:
        return [
            "## Documentation scope",
            "",
            "This README is generated from static repository evidence. It does not claim runtime behavior that was not identified in manifests, source layout, tests, or CI configuration.",
            "",
        ]

    def _normalize(self, text: str) -> str:
        text = re.sub(r"\n{3,}", "\n\n", text.strip())
        return text + "\n"
